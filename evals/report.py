"""The results summary as a deliverable. Built from ids and numbers, so there is no field a name could reach."""

from dataclasses import dataclass, field
from statistics import mean

from evals.ablation import AblationRow
from evals.scoring import Gate, Label, RunOutcome, by_applicant


@dataclass(frozen=True)
class Report:
    """Everything the summary states, and nothing it would have to redact."""

    commit: str
    model: str
    runs: int
    brain_version: str
    brain_hash: str
    naive_version: str
    watchlist_hash: str
    gates: list[Gate]
    outcomes: list[RunOutcome]
    labels: dict[str, Label]
    ablation: list[AblationRow]
    unlabelled: list[str] = field(default_factory=list)


def render(report: Report) -> str:
    """One markdown document, regenerated rather than edited."""
    return "\n".join(
        [
            "# Eval results",
            "",
            "Regenerated by `uv run python evals/run_evals.py`. Every number here is a",
            "measurement of the state named in the table below, not of the repository in",
            "general — a results table that does not say which policy produced it is a",
            "screenshot.",
            "",
            *_state(report),
            "",
            "## Gates",
            "",
            *_gates(report),
            "",
            "## The labelled dev set",
            "",
            *_applicants(report),
            "",
            "## The override ablation",
            "",
            "The same packet, the same facts and the same code path under two rule tables.",
            "No model is involved, so this table costs nothing and is checked on every run",
            "of the offline suite as well as here (D-014).",
            "",
            *_ablation(report),
            "",
            "## The override, against the live model",
            "",
            "The proposal carries the naive base heuristic the policy permits, sees the facts",
            "and the tool's own output, and never the rule table (D-010). It is recorded on",
            "every run, agreement included — a field that only appears on disagreement is a",
            "demonstration mode rather than an instrument.",
            "",
            *_override(report),
            "",
            "## Reported, never gated",
            "",
            *_reported(report),
            "",
            "## The six unlabelled applicants",
            "",
            "No ground truth exists for these, so nothing here is scored. They are screened",
            "by the deterministic path only — the floor, the sweep and the rule table, with",
            "no model call — which is why they cost nothing to report. The property that",
            "matters for them is structural and is gated above: a hit that clears is a false",
            "clear whether or not anybody labelled it (D-015).",
            "",
            *_unlabelled(report),
            "",
        ]
    )


def _state(report: Report) -> list[str]:
    return [
        "| | |",
        "|---|---|",
        f"| commit | `{report.commit}` |",
        f"| model | `{report.model}` |",
        f"| runs per applicant | {report.runs} |",
        f"| policy | `{report.brain_version}` at `{report.brain_hash}` |",
        f"| baseline | `{report.naive_version}` |",
        f"| watchlist | `{report.watchlist_hash}` |",
    ]


def _gates(report: Report) -> list[str]:
    rows = [
        f"| `{gate.name}` | {'pass' if gate.passed else '**FAIL**'} | {gate.detail} |" for gate in report.gates
    ]
    return ["| gate | result | detail |", "|---|---|---|", *rows]


def _applicants(report: Report) -> list[str]:
    rows = []
    for applicant_id, runs in sorted(by_applicant(report.outcomes).items()):
        decisions = sorted({run.decision for run in runs})
        rules = sorted({rule for run in runs for rule in run.fired_rules})
        serialisations = len({run.fingerprint for run in runs})
        rows.append(
            f"| {applicant_id} | {report.labels[applicant_id].decision} | {'/'.join(decisions)} | "
            f"{', '.join(str(rule) for rule in rules)} | {serialisations} | "
            f"${mean(run.cost_usd for run in runs):.4f} | {mean(run.duration_ms for run in runs) / 1000:.1f}s |"
        )
    return [
        "| applicant | expected | reached | rules fired | serialisations | cost/run | latency/run |",
        "|---|---|---|---|---|---|---|",
        *rows,
    ]


def _ablation(report: Report) -> list[str]:
    rows = [
        f"| {row.applicant_id} | {row.live} ({', '.join(str(rule) for rule in row.live_rules)}) | "
        f"{'**' + row.naive + '**' if row.disagrees else row.naive} | {row.guardrail} |"
        for row in report.ablation
    ]
    disagreeing = [row for row in report.ablation if row.disagrees]
    caught = [row for row in disagreeing if row.guardrail == "raises"]
    return [
        f"| applicant | `{report.brain_version}` | `{report.naive_version}` | guardrail under the baseline |",
        "|---|---|---|---|",
        *rows,
        "",
        f"The two disagree on **{len(disagreeing)} of {len(report.ablation)}** packets, every one of them in the",
        f"CLEAR direction. The never-auto-CLEAR guardrail refuses **{len(caught)}** of those — the ones carrying a",
        f"watchlist hit — and serves the other **{len(disagreeing) - len(caught)}**, where the correct verdict comes",
        "from high-risk activity, missing documents or shell signals instead. A runtime",
        "guardrail is a net under one class of failure, not under a wrong policy.",
    ]


def _reported(report: Report) -> list[str]:
    outcomes = report.outcomes
    cached = sum(run.cached_input_tokens for run in outcomes)
    fresh = sum(run.input_tokens for run in outcomes)
    cache_ratio = f"{100 * cached / (cached + fresh):.1f}%" if cached + fresh else "not reported"
    return [
        "| | |",
        "|---|---|",
        f"| runs | {len(outcomes)} over {len(by_applicant(outcomes))} applicants |",
        f"| cost | ${sum(run.cost_usd for run in outcomes):.4f} total, "
        f"${mean(run.cost_usd for run in outcomes):.4f} per applicant |",
        f"| latency | {mean(run.duration_ms for run in outcomes) / 1000:.1f}s per applicant |",
        f"| input from cache | {cache_ratio} ({cached} cached / {fresh} fresh) |",
        f"| output | {sum(run.output_tokens for run in outcomes) // max(len(outcomes), 1)} tokens per run |",
        f"| model-initiated searches | {sum(run.searches for run in outcomes)} |",
        f"| hits the loop added | {sum(run.hits_added for run in outcomes)} "
        f"(and {sum(run.hits_redundant for run in outcomes)} redundant, dropped by D-013) |",
    ]


def _override(report: Report) -> list[str]:
    """Which applicants the Brain actually overruled, and what the model had proposed instead."""
    overruled = [run for run in report.outcomes if run.overridden]
    if not overruled:
        return ["No run disagreed. The Brain and the naive proposal reached the same decision every time."]

    rows = []
    for applicant_id, runs in sorted(by_applicant(overruled).items()):
        total = len(by_applicant(report.outcomes)[applicant_id])
        proposed = "/".join(sorted({run.proposed or "none" for run in runs}))
        final = "/".join(sorted({run.decision for run in runs}))
        rows.append(f"| {applicant_id} | {len(runs)} of {total} | {proposed} | **{final}** |")

    return [
        "| applicant | runs overruled | the model proposed | the Brain decided |",
        "|---|---|---|---|",
        *rows,
        "",
        f"{len(overruled)} of {len(report.outcomes)} runs were overruled.",
    ]


def _unlabelled(report: Report) -> list[str]:
    rows = [
        f"| {row.applicant_id} | {row.live} ({', '.join(str(rule) for rule in row.live_rules)}) |"
        for row in report.ablation
        if row.applicant_id in report.unlabelled
    ]
    return ["| applicant | decision |", "|---|---|", *rows]
